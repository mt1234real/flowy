  static String normalize(String value) {
    var result = value.toLowerCase().trim();
    const groups = {
      'a': 'àáạảãâầấậẩẫăằắặẳẵ',
      'e': 'èéẹẻẽêềếệểễ',
      'i': 'ìíịỉĩ',
      'o': 'òóọỏõôồốộổỗơờớợởỡ',
      'u': 'ùúụủũưừứựửữ',
      'y': 'ỳýỵỷỹ',
      'd': 'đ',
    };
    groups.forEach((plain, accents) {
      for (final rune in accents.runes) {
        result = result.replaceAll(String.fromCharCode(rune), plain);
      }
    });
    return result
        .replaceAll(RegExp(r'[\u0300-\u036f]'), '')
        .replaceAll(RegExp(r'\s+'), ' ');
  }

  static final _searchIndex = {
    for (final item in all)
      item.key:
          normalize('${item.key} ${item.label} ${item.keywords.join(' ')}')
  };
  static List<AppIconItem> search(String query, {String topic = 'Tất cả'}) {
    final words =
        normalize(query).split(' ').where((word) => word.isNotEmpty).toList();
    return all
        .where((item) =>
            (topic == 'Tất cả' ||
                item.topic == topic ||
                item.alsoTopics.contains(topic)) &&
            words.every((word) => _searchIndex[item.key]!.contains(word)))
        .toList(growable: false);
  }

  static Color parseColor(String? hex,
      {Color fallback = const Color(0xFF10B981)}) {
    final clean = (hex ?? '').trim().replaceFirst('#', '');
    if (!RegExp(r'^[0-9a-fA-F]{6}$').hasMatch(clean)) return fallback;
    return Color(0xFF000000 | int.parse(clean, radix: 16));
  }

